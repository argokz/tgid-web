/** Имя как в шаблоне: `mdi-cog` или как экспорт MDI: `mdiCog` */

export function resolveMdiSvgPath(rawName: string): string {

  if (!rawName) return ''

  if (/^mdi[A-Z]/.test(rawName)) {

    return byExportName[rawName] ?? ''

  }

  const camelKey = rawName

    .replace(/^mdi-/, '')

    .replace(/-([a-z])/g, (_: string, c: string) => c.toUpperCase())

  const iconKey = 'mdi' + camelKey.charAt(0).toUpperCase() + camelKey.slice(1)

  return byExportName[iconKey] ?? ''

}

