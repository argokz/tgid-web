/** Ленивый набор; null — ещё не загружен (и всегда на сервере: SSR и гидратация видят только первый экран) */
const lazyMdiSvgPaths = shallowRef<Record<string, string> | null>(null)
let lazyLoad: Promise<void> | null = null

/** Грузит иконки диалогов и журналов. Повторный вызов отдаёт ту же загрузку; после ошибки — пробует заново */
export function loadLazyMdiSvgPaths(): Promise<void> {
  if (import.meta.server) return Promise.resolve()
  lazyLoad ??= import('./mdiSvgPathsLazy')
    .then((m) => {
      lazyMdiSvgPaths.value = m.lazyMdiSvgPaths
    })
    .catch((error: unknown) => {
      lazyLoad = null
      throw error
    })
  return lazyLoad
}

/** Имя как в шаблоне: `mdi-cog` или как экспорт MDI: `mdiCog` → `mdiCog` */
export function toMdiExportName(rawName: string): string {
  if (/^mdi[A-Z]/.test(rawName)) return rawName
  const camelKey = rawName
    .replace(/^mdi-/, '')
    .replace(/-([a-z0-9])/g, (_: string, c: string) => c.toUpperCase())
  return 'mdi' + camelKey.charAt(0).toUpperCase() + camelKey.slice(1)
}

/**
 * SVG-путь иконки; '' — нет такой или ленивый набор ещё не загружен. Чтение ленивого набора реактивно:
 * компонент иконки Vuetify перерисуется, когда набор придёт.
 */
export function resolveMdiSvgPath(rawName: string): string {
  if (!rawName) return ''
  const key = toMdiExportName(rawName)
  return firstScreenMdiSvgPaths[key] ?? lazyMdiSvgPaths.value?.[key] ?? ''
}
