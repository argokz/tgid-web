/**
 * Брейкпоинты — один источник для TS и SCSS (зеркало `$breakpoint-*` в `assets/styles/_variables.scss`,
 * совпадение проверяет `tests/styles/tokens.spec.ts`).
 *
 * Значения — Vuetify display (`sm` 600, `md` 960, `lg` 1280): на них сами переключаются компоненты Vuetify
 * (`useDisplay`, полноэкранные диалоги, утилиты `d-sm-*`), и 23 из 29 медиазапросов проекта уже писались
 * под 600 и 960. Старые 768/1024 из `useMobile` и 768 из SCSS убраны — два набора давали разные раскладки
 * у Vue-логики и у стилей на одной и той же ширине.
 *
 * Матрица устройств из плана модернизации:
 * - `phone` < 960: телефон в обоих положениях и планшет портретом — одна панель на экране, окна во весь экран;
 * - `tablet` 960–1279: планшет альбомом, маленький ноутбук — панели рядом с картой, окна обычные;
 * - `desktop` ≥ 1280: ноутбук и мониторы диспетчерских.
 */
export const BREAKPOINTS = Object.freeze({
  /** Телефон портретом — ниже; телефон альбомом / планшет портретом — выше */
  sm: 600,
  /** Граница «телефонной» подачи (одна панель, окна во весь экран) */
  md: 960,
  /** Граница настольной подачи */
  lg: 1280,
});

export type DeviceClass = 'phone' | 'tablet' | 'desktop';

/** Класс устройства по ширине окна; 0 (SSR, окно ещё не измерено) — считается телефоном, вызывающий код это проверяет */
export function deviceClass(width: number): DeviceClass {
  if (width < BREAKPOINTS.md) return 'phone';
  if (width < BREAKPOINTS.lg) return 'tablet';
  return 'desktop';
}
